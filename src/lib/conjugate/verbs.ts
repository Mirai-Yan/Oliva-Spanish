/**
 * Verb class data. Verbs not listed here conjugate regularly (orthographic changes such as
 * c→qu, g→j, -uir → y, vowel+cer → zc are detected automatically from the infinitive).
 */

export type StemChange = 'ie' | 'ie0' | 'ue' | 'i' | 'uue' | 'iie' | 'acc-i' | 'acc-u'
export type Six = [string, string, string, string, string, string]

export interface VerbSpec {
  stem?: StemChange
  /** irregular 1st person present; subjunctive present is built from it */
  yo?: string
  /** strong preterite stem (tuv-, pud-, dij-…) */
  pretStem?: string
  /** irregular future/conditional stem (tendr-, har-…) */
  futStem?: string
  subjStem?: string
  part?: string
  ger?: string
  impTu?: string
  /** disable automatic zc for vowel+cer verbs (cocer, mecer) */
  noZc?: boolean
  /** tenses the verb does not have (soler has no future…) */
  defective?: string[]
  over?: Partial<Record<string, Six | Partial<Record<number, string>>>>
}

